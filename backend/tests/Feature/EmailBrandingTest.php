<?php

declare(strict_types=1);

use App\Mail\OrderStatusMail;
use App\Mail\RestockAvailableMail;
use App\Models\Product;
use App\Models\ProductVariant;
use App\Models\User;
use App\Notifications\ResetPasswordNotification;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Notification;
use Illuminate\Support\Facades\Password;

beforeEach(function (): void {
    config(['app.frontend_url' => 'https://misturafeminina.com.br']);
});

function assertBrandedEmail(string $html, string $previewName): void
{
    expect($html)->toContain('https://misturafeminina.com.br/logo-mf.png', 'alt="Mistura Feminina"', '#93509e', 'max-width:600px', 'name="viewport"', 'lang="pt-BR"');
    if ($previewDirectory = getenv('EMAIL_PREVIEW_DIR')) {
        file_put_contents($previewDirectory.'/'.$previewName.'.html', $html);
    }
}

test('password recovery uses Portuguese branding and the configured expiry', function (int $minutes): void {
    config(['auth.passwords.'.config('auth.defaults.passwords').'.expire' => $minutes]);
    $user = User::factory()->create(['email' => 'ana+loja@example.com']);
    $mail = (new ResetPasswordNotification('token-teste'))->toMail($user);
    $html = (string) $mail->render();
    assertBrandedEmail($html, 'reset');
    expect($mail->subject)->toBe('Redefina sua senha | Mistura Feminina');
    expect($html)->toContain('Redefinir minha senha', 'Se você não solicitou', '<strong>'.$minutes.' '.($minutes === 1 ? 'minuto' : 'minutos').'</strong>')
        ->not->toContain('Hello!', 'Reset Password', 'Regards');
    $url = $mail->viewData['resetUrl'];
    parse_str(parse_url($url, PHP_URL_QUERY), $query);
    expect($query)->toBe(['token' => 'token-teste', 'email' => $user->email]);
    expect(substr_count($html, 'href="'.htmlspecialchars($url, ENT_QUOTES, 'UTF-8').'"'))->toBe(2);
})->with([1, 45]);

test('a recovery link generated by the branded notification resets the password', function (): void {
    Notification::fake();
    $user = User::factory()->create();
    $this->postJson('/forgot-password', ['email' => $user->email])->assertOk();
    $notification = Notification::sent($user, ResetPasswordNotification::class)->first();
    expect($notification)->toBeInstanceOf(ResetPasswordNotification::class);
    parse_str(parse_url($notification->toMail($user)->viewData['resetUrl'], PHP_URL_QUERY), $query);
    $this->postJson('/reset-password', [
        ...$query, 'password' => 'NovaSenhaSegura@2026', 'password_confirmation' => 'NovaSenhaSegura@2026',
    ])->assertOk();
    expect(Hash::check('NovaSenhaSegura@2026', $user->fresh()->password))->toBeTrue();
});

test('expired recovery tokens remain invalid', function (): void {
    $user = User::factory()->create();
    $token = Password::createToken($user);
    $minutes = (int) config('auth.passwords.'.config('auth.defaults.passwords').'.expire');
    $this->travel($minutes + 1)->minutes();
    $this->postJson('/reset-password', [
        'token' => $token, 'email' => $user->email,
        'password' => 'NovaSenhaSegura@2026', 'password_confirmation' => 'NovaSenhaSegura@2026',
    ])->assertUnprocessable();
});

test('order emails share the branding and preserve totals and tracking', function (): void {
    $html = (new OrderStatusMail([
        'headline' => 'Seu pedido está a caminho!', 'body' => 'Seu pedido foi enviado. Acompanhe a entrega abaixo.',
        'customer_name' => 'Ana', 'order_number' => 'MF-20261126-001', 'status_label' => 'Enviado',
        'total_cents' => 11490, 'shipping_cents' => 1500, 'discount_cents' => 0,
        'items' => [['name' => 'Hidratante facial', 'variant' => '120 ml', 'quantity' => 1, 'total_cents' => 9990]],
        'tracking_code' => 'AA123456789BR', 'carrier' => 'Correios',
        'tracking_url' => 'https://rastreamento.correios.com.br/', 'tracking_page_url' => null,
        'order_url' => 'https://misturafeminina.com.br/pedido/token-teste/confirmacao',
    ]))->render();
    assertBrandedEmail($html, 'order');
    expect($html)->toContain('Hidratante facial', 'R$ 114,90', 'AA123456789BR', 'https://rastreamento.correios.com.br/', 'Acompanhar pedido');
});

test('restock emails share the branding and preserve the product link', function (): void {
    $product = new Product(['name' => 'Hidratante facial', 'slug' => 'hidratante-facial']);
    $variant = new ProductVariant(['name' => '120 ml']);
    $html = (new RestockAvailableMail($product, $variant))->render();
    assertBrandedEmail($html, 'restock');
    expect($html)->toContain('Hidratante facial', '120 ml', 'Ver produto na loja', 'https://misturafeminina.com.br/produto/hidratante-facial');
});
